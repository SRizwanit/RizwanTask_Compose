--    (ফোন নাম্বার মিলিয়ে)। তাই এখানে anon-কে সব টেবিলে পূর্ণ অ্যাক্সেস দেওয়া হলো, নইলে অ্যাপ চলবে না।
--    ⚠ নিরাপত্তা ঝুঁকি: app_settings-এ github_token ও gemini_api_key আছে — anon key থাকলে যে কেউ পড়তে পারবে।
--       প্রোডাকশনের জন্য এগুলো Edge Function/সার্ভারে সরানো ও Supabase Auth + ভূমিকাভিত্তিক policy করা উচিত।
-- =====================================================================
do $$
declare t text;
begin
  foreach t in array array['app_users','otp_codes','app_settings','books','page_proofs',
                           'payments','notices','activity_log','book_locks']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "rt_all_access" on public.%I', t);
    execute format('create policy "rt_all_access" on public.%I for all to anon, authenticated using (true) with check (true)', t);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', t);
  end loop;
end $$;
-- identity সিকোয়েন্সে insert-এর অনুমতি
grant usage, select on all sequences in schema public to anon, authenticated;


