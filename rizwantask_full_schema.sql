-- ইউজারের নিজের মোট প্রুফড পেইজ
create or replace function public.my_proof_count(p_user text)
returns bigint
language sql stable
as $$
  select count(*) from public.page_proofs where user_id::text = p_user;
$$;
grant execute on function public.my_proof_count(text) to anon, authenticated;

-- কিতাব অনুযায়ী মোট প্রুফড পেইজ (অগ্রগতির বার)
create or replace function public.book_proof_counts()
returns table(book_id text, n bigint)
language sql stable
as $$ select book_id::text, count(*) from public.page_proofs group by book_id; $$;
grant execute on function public.book_proof_counts() to anon, authenticated;

-- লিডারবোর্ড ("সংশোধন দরকার" বাদে); p_since = কোন সময় থেকে (null = সব সময়)
create or replace function public.leaderboard(p_since timestamptz default null)
returns table(user_id text, n bigint)
language sql stable
as $$
  select user_id::text, count(*) from public.page_proofs
  where review_status <> 'correction' and (p_since is null or created_at >= p_since)
  group by user_id order by count(*) desc limit 200;
$$;
grant execute on function public.leaderboard(timestamptz) to anon, authenticated;

-- লক: নিজের beat দেয়। অন্য কেউ সক্রিয় থাকলে তার নাম ফেরত (text), নইলে null এবং লক নিজের নামে।
create or replace function public.book_lock_beat(p_book text, p_user text, p_name text default '')
returns text
language plpgsql
as $$
declare r public.book_locks%rowtype;
begin
  select * into r from public.book_locks where book_id = p_book;
  if found and r.user_id <> p_user and r.beat_at > now() - interval '60 seconds' then
    return coalesce(nullif(r.user_name, ''), 'অন্য একজন ইউজার');
  end if;
  insert into public.book_locks (book_id, user_id, user_name, beat_at)
  values (p_book, p_user, p_name, now())
  on conflict (book_id) do update
    set user_id = excluded.user_id, user_name = excluded.user_name, beat_at = now();
  return null;
end;
$$;
grant execute on function public.book_lock_beat(text, text, text) to anon, authenticated;

-- লক: বর্তমান সক্রিয় ধারক (থাকলে ১টি সারি: holder_id, holder_name)
create or replace function public.book_lock_of(p_book text)
returns table(holder_id text, holder_name text)
language sql stable
as $$
  select user_id, user_name from public.book_locks
  where book_id = p_book and beat_at > now() - interval '60 seconds';
$$;
grant execute on function public.book_lock_of(text) to anon, authenticated;

-- লক: নিজের লক ছেড়ে দেওয়া
create or replace function public.book_lock_release(p_book text, p_user text)
returns void
language sql
as $$
  delete from public.book_locks where book_id = p_book and user_id = p_user;
$$;
grant execute on function public.book_lock_release(text, text) to anon, authenticated;


