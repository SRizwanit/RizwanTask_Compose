/**
 * React task/guideScenes.js — the `GUIDE` list (3-ঙ-২): the first-time guide, step by step.
 * [tag] = the golden label, [t] = title, [d] = text, [subs] = numbered sub-steps (lit one by one while the scene plays),
 * [sc] = makes the scene. All scenes are written: `shotScene` (GuideShot.kt), `sceneWelcome`, `sceneBook`, `sceneEarn`, `sceneGoal`,
