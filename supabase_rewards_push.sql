-- =====================================================================
-- ১০-খ) reward_badges — সাপ্তাহিক / মাসিক রিওয়ার্ড ব্যাজ (র‍্যাংকে দেখায়)
--    প্রতিটি শেষ হওয়া সপ্তাহ (শনিবার–শুক্রবার, Asia/Dhaka) ও মাসের সেরা ৩ জন ব্যাজ পান।
--    গণনা: "সংশোধন দরকার" বাদে প্রুফড পেইজ; সমান হলে যিনি আগে শুরু করেছেন তিনি এগিয়ে।
--    ন্যূনতম পেইজ (না হলে ব্যাজ নেই): সপ্তাহে ১০, মাসে ৩০ — award_rewards()-এর ডিফল্ট প্যারামিটারে বদলান।
--    অ্যাপ র‍্যাংক খুললে award_rewards() কল করে; বারবার কল করলেও ডুপ্লিকেট হয় না (unique constraint)।
--    নতুন ব্যাজ পেলে বিজয়ীর নামে notices (kind = 'reward') সারি তৈরি হয় → অ্যাপে পুশ নোটিফিকেশন যায়।
--    period_type: week | month ; place: ১ = স্বর্ণ, ২ = রৌপ্য, ৩ = ব্রোঞ্জ
-- =====================================================================
create table if not exists public.reward_badges (
  id           bigint generated by default as identity primary key,
  period_type  text not null check (period_type in ('week', 'month')),
  period_start date not null,                       -- সপ্তাহের শনিবার / মাসের ১ তারিখ (Asia/Dhaka)
  user_id      text not null,
  place        integer not null check (place between 1 and 10),
  pages        integer not null default 0,
  created_at   timestamptz not null default now(),
  unique (period_type, period_start, user_id)
);
create index if not exists reward_badges_user_idx   on public.reward_badges (user_id);
create index if not exists reward_badges_period_idx on public.reward_badges (period_type, period_start desc);

create or replace function public.award_rewards(
  p_top       integer default 3,
  p_min_week  integer default 10,
  p_min_month integer default 30
)
returns integer
language plpgsql
as $$
declare
  tz       constant text := 'Asia/Dhaka';
  v_today  date := (now() at time zone tz)::date;
  v_week   date := v_today - ((extract(isodow from v_today)::int + 1) % 7);   -- চলতি সপ্তাহের শনিবার
  v_month  date := date_trunc('month', v_today::timestamp)::date;
  r        record;
  v_new    integer;
  v_total  integer := 0;
begin
  for r in
    select 'week'::text as t, (v_week - 7 * k) as ps, (v_week - 7 * k + 7) as pe, p_min_week as mn
      from generate_series(1, 4) k
    union all
    select 'month'::text, (v_month - make_interval(months => k))::date, (v_month - make_interval(months => k - 1))::date, p_min_month
      from generate_series(1, 3) k
  loop
    with ranked as (
      select user_id::text as uid, count(*)::integer as n, min(created_at) as first_at
        from public.page_proofs
       where coalesce(review_status, '') <> 'correction'
         and created_at >= (r.ps::timestamp at time zone tz)
         and created_at <  (r.pe::timestamp at time zone tz)
       group by user_id
      having count(*) >= r.mn
    ), top as (
      select uid, n, row_number() over (order by n desc, first_at asc)::integer as place from ranked
    ), ins as (
      insert into public.reward_badges (period_type, period_start, user_id, place, pages)
      select r.t, r.ps, uid, place, n from top where place <= p_top
      on conflict (period_type, period_start, user_id) do nothing
      returning user_id, place, pages
    ), nn as (
      insert into public.notices (user_id, title, body, kind)
      select user_id,
             case when r.t = 'week' then 'সাপ্তাহিক রিওয়ার্ড ব্যাজ' else 'মাসিক রিওয়ার্ড ব্যাজ' end,
             'অভিনন্দন! ' ||
             case when r.t = 'week'
                  then 'গত সপ্তাহে (' || to_char(r.ps, 'DD/MM') || ' – ' || to_char(r.pe - 1, 'DD/MM') || ')'
                  else 'গত মাসে (' || to_char(r.ps, 'MM/YYYY') || ')' end ||
             ' ' || translate(pages::text, '0123456789', '০১২৩৪৫৬৭৮৯') || ' পেইজ প্রুফ করে আপনি ' ||
             case place when 1 then '১ম' when 2 then '২য়' when 3 then '৩য়' else translate(place::text, '0123456789', '০১২৩৪৫৬৭৮৯') || ' নম্বর' end ||
             ' স্থান অর্জন করেছেন — র‍্যাংক ট্যাবে আপনার ব্যাজ দেখুন।',
             'reward'
        from ins
      returning 1
    )
    select (select count(*) from ins) + (select count(*) from nn) * 0 into v_new;
    v_total := v_total + coalesce(v_new, 0);
  end loop;
  return v_total;
end;
$$;
grant execute on function public.award_rewards(integer, integer, integer) to anon, authenticated;


alter table public.reward_badges enable row level security;
drop policy if exists "rt_all_access" on public.reward_badges;
create policy "rt_all_access" on public.reward_badges for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.reward_badges to anon, authenticated;
